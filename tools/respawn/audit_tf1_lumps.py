import argparse
import json
from pathlib import Path
import re
import struct

from inspect_bsp import FormatError, inspect
from validate_records import SCHEMAS, TF1_SCHEMAS, validate

WRITER = Path(__file__).resolve().parents[1] / 'remap/source/titanfall/titanfall.cpp'


def writer_lumps(source):
    """Include conditional writes and the separately serialized static-prop GAME_LUMP."""
    return set(re.findall(r'AddLump\(file,\s*header\.lumps\[R1_LUMP_(\w+)\]', source)) | {'GAME_LUMP'}


def audit(paths, source):
    maps = []
    for path in paths:
        inventory = inspect(path, hashes=True)
        if inventory['version_raw'] != 29 or inventory['byte_order'] != 'little':
            raise FormatError(f'{path}: expected little-endian BSP v29')
        try:
            validation = validate(path)
        except (OSError, ValueError) as exc:
            validation = {'issues': [{'severity': 'error', 'message': str(exc)}]}
        maps.append((inventory, validation))
    written = writer_lumps(source)
    rows = []
    for index in range(128):
        entries = [inv['lumps'][index] for inv, _ in maps]
        name = entries[0]['name']
        # Some name tables include the R1_LUMP prefix, others contain bare names.
        bare_name = (name or '').removeprefix('R1_LUMP_')
        if bare_name not in written and not any(e['length'] or e['external_files'] for e in entries):
            continue
        schema = (SCHEMAS | TF1_SCHEMAS).get(index)
        observations = []
        for (inv, _), entry in zip(maps, entries):
            external = next((e for e in entry['external_files'] if e['variant'] == 'default'), None)
            size = external['size'] if external else entry['length']
            observation = {'map': inv['path'], 'bytes': size, 'version': entry['version'],
                           'storage': entry['storage'],
                           'sha256': (external or entry).get('sha256')}
            if schema and size:
                stride = struct.calcsize('<' + schema[0])
                observation.update(record_bytes=stride, records=size // stride,
                                   remainder=size % stride, schema_version_matches=entry['version'] == schema[1])
            observations.append(observation)
        rows.append({'index': index, 'name': bare_name, 'writer': bare_name in written,
                     'record_schema': schema is not None, 'semantic_parity': 'unverified',
                     'observations': observations})
    return {'scope': 'Directory, writer coverage and selected record checks only; runtime and semantic parity are separate.',
            'writer_lump_count': len(written), 'lumps': rows,
            'maps': [{'path': inv['path'], 'inventory_issues': inv['issues'],
                      'record_issues': validation['issues']} for inv, validation in maps]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('maps', nargs='+', type=Path)
    parser.add_argument('--writer', type=Path, default=WRITER)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--markdown', type=Path, help='Also write a reviewable per-lump checklist')
    args = parser.parse_args()
    report = audit(args.maps, args.writer.read_text(encoding='utf-8'))
    args.output.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    if args.markdown:
        lines = ['# v29 lump coverage inventory', '',
                 'Generated by `audit_tf1_lumps.py`. Every semantic parity status remains **unverified**.',
                 'A record schema means selected structural checks exist, not that every field is understood.',
                 'Bytes below prefer the default external sidecar when present. Empty payloads cannot validate a layout.', '',
                 '| ID | Lump | Writer | Record schema | ' + ' | '.join(Path(p).stem for p in args.maps) + ' |',
                 '| --- | --- | --- | --- | ' + ' | '.join('---' for _ in args.maps) + ' |']
        for row in report['lumps']:
            values = [f"{o['bytes']} B / v{o['version']}" if o['bytes'] else 'empty' for o in row['observations']]
            lines.append('| ' + ' | '.join([str(row['index']), row['name'], 'yes' if row['writer'] else 'no',
                                             'yes' if row['record_schema'] else 'no'] + values) + ' |')
        args.markdown.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f"{len(report['maps'])} maps, {report['writer_lump_count']} writer lumps; see {args.output}")
    return int(any(issue.get('severity') == 'error' for result in report['maps']
                   for field in ('inventory_issues', 'record_issues') for issue in result[field]))


if __name__ == '__main__':
    raise SystemExit(main())
